#!/usr/bin/env bun

/// <reference types="bun" />

import { Database } from "bun:sqlite";
import { expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync } from "node:fs";
import { join, resolve } from "node:path";

interface SpawnedGateway {
	stdout: ReadableStream<Uint8Array>;
	stderr: ReadableStream<Uint8Array>;
	exited: Promise<number | null>;
	kill(signal?: string): void;
}

interface OutputBuffer {
	stdout: string[];
	stderr: string[];
}

interface OutboxPayload {
	messages?: Array<{
		conversationId?: string;
		text?: string;
	}>;
}

const repoRoot = resolve(import.meta.dir, "..");
const dumbClientPath = join(
	repoRoot,
	"packages",
	"acp-dumb-client",
	"src",
	"main.ts",
);
const cliPath = join(repoRoot, "packages", "cli", "src", "main.ts");
const promptText = "hello from the e2e bench";
const expectedReply = `dumb client: ${promptText}`;

interface E2eOptions {
	agentArgs?: string[];
	auth?: { methodId: string };
	state?: { path: string };
}

test("routes webhook events through the SDK-backed dumb ACP client", async () => {
	await runE2e();
}, 20_000);

test("authenticates the configured agent before serving webhook events", async () => {
	await runE2e({
		agentArgs: ["--auth-method", "api-key"],
		auth: { methodId: "api-key" },
	});
}, 20_000);

test("re-establishes the session after a gateway restart (shared sqlite state)", async () => {
	const tempRoot = join(repoRoot, "out");
	mkdirSync(tempRoot, { recursive: true });
	const tempDir = mkdtempSync(join(tempRoot, "acpantenna-reconnect-"));
	const configPath = join(tempDir, "acpantenna.config.ts");
	const statePath = join(tempDir, "state.sqlite");

	try {
		await writeConfig(configPath, { state: { path: statePath } });

		const first = await startGateway(configPath);
		try {
			await postWebhookEvent(first.baseUrl, "first", "reconnect");
			await waitForOutboxReply(first.baseUrl, "dumb client: first");
		} finally {
			await stopGateway(first.process);
		}

		// Restart: a brand-new agent process that has never heard of the session
		// id persisted in the shared SQLite store. Without the reconnect ladder,
		// prompting the stale id would fail.
		const second = await startGateway(configPath);
		try {
			await postWebhookEvent(second.baseUrl, "second", "reconnect");
			await waitForOutboxReply(second.baseUrl, "dumb client: second");
		} finally {
			await stopGateway(second.process);
		}
	} finally {
		rmSync(tempDir, { recursive: true, force: true });
	}
}, 30_000);

test("an embedding host's JSON config and existing database serve as before", async () => {
	const tempRoot = join(repoRoot, "out");
	mkdirSync(tempRoot, { recursive: true });
	const tempDir = mkdtempSync(join(tempRoot, "acpantenna-embedded-"));
	const configPath = join(tempDir, "bridge.config.json");
	const statePath = join(tempDir, "bridge.sqlite");
	const old = new Database(statePath, { create: true });

	// The sessions table as the first release made it, with one conversation.
	old.run(`
      create table sessions (
        channel_id text not null,
        session_key text not null,
        agent_id text not null,
        acp_session_id text not null,
        conversation_id text not null,
        updated_at text not null,
        primary key (channel_id, session_key)
      )
    `);
	old
		.query("insert into sessions values (?, ?, ?, ?, ?, ?)")
		.run(
			"phone",
			"phone:conversation:room-1",
			"main",
			"session-from-before",
			"room-1",
			new Date().toISOString(),
		);
	old.close();

	// A config generated by a host that runs acpantenna: JSON, one agent,
	// permissions asked in the conversation.
	await Bun.write(
		configPath,
		JSON.stringify({
			server: { host: "127.0.0.1", port: 0 },
			agents: {
				main: {
					command: "bun",
					args: [dumbClientPath, "--resume", "--echo-context"],
					cwd: repoRoot,
					default: true,
				},
			},
			defaults: { session: { rehydrateOnStart: true } },
			channels: {
				phone: {
					type: "webhook",
					agent: "main",
					permissions: {
						inbound: { mode: "allowlist", allow: ["bench-user"] },
						toolCalls: "ask",
						interactionTimeoutSeconds: 1800,
					},
				},
			},
			state: { driver: "sqlite", path: statePath },
		}),
	);

	const gateway = await startGateway(configPath);

	try {
		const status = (await (
			await fetch(new URL("/status", gateway.baseUrl))
		).json()) as Record<string, unknown>;

		expect(status).toEqual({
			ok: true,
			// The built-in latch channel is there too; it does nothing until a connect.
			channels: {
				latch: { type: "relay", state: "ready" },
				phone: { type: "webhook", state: "ready" },
			},
			agents: { main: { state: expect.any(String) } },
		});
		// Connections are managed through the user's own server, never `serve`.
		expect((await fetch(new URL("/connections", gateway.baseUrl))).status).toBe(
			404,
		);

		await assertResponseOk(
			await fetch(new URL("/channels/phone/events", gateway.baseUrl), {
				method: "POST",
				headers: { "content-type": "application/json" },
				body: JSON.stringify({
					text: "hi",
					senderId: "bench-user",
					conversationId: "room-1",
				}),
			}),
			"webhook event",
		);

		const deadline = Date.now() + 10_000;
		let texts: string[] = [];

		while (Date.now() < deadline) {
			const outbox = (await (
				await fetch(new URL("/channels/phone/outbox", gateway.baseUrl))
			).json()) as OutboxPayload;
			texts = (outbox.messages ?? []).flatMap((message) =>
				message.text ? [message.text] : [],
			);

			if (texts.length > 0) {
				break;
			}

			await Bun.sleep(50);
		}

		// The conversation carried on in the session it had, not a new one.
		expect(texts).toEqual([
			`[session-from-before ${repoRoot}] dumb client: hi`,
		]);
	} finally {
		await stopGateway(gateway.process);
		rmSync(tempDir, { recursive: true, force: true });
	}
}, 30_000);

async function runE2e(options: E2eOptions = {}): Promise<void> {
	const tempRoot = join(repoRoot, "out");
	mkdirSync(tempRoot, { recursive: true });
	const tempDir = mkdtempSync(join(tempRoot, "acpantenna-e2e-"));
	const configPath = join(tempDir, "acpantenna.config.ts");
	let gateway: StartedGateway | undefined;

	try {
		await writeConfig(configPath, options);
		gateway = await startGateway(configPath);
		await postWebhookEvent(gateway.baseUrl, promptText, "bench-conversation");
		const reply = await waitForOutboxReply(gateway.baseUrl, expectedReply);
		console.log(`acpantenna e2e bench passed: ${reply.text}`);
	} finally {
		if (gateway) {
			await stopGateway(gateway.process);
		}

		rmSync(tempDir, { recursive: true, force: true });
	}
}

interface StartedGateway {
	process: SpawnedGateway;
	baseUrl: URL;
}

async function startGateway(configPath: string): Promise<StartedGateway> {
	const process = Bun.spawn({
		cmd: [
			"bun",
			"run",
			cliPath,
			"serve",
			"--config",
			configPath,
			"--server",
			"127.0.0.1:0",
		],
		cwd: repoRoot,
		stdin: "ignore",
		stdout: "pipe",
		stderr: "pipe",
	}) as SpawnedGateway;

	const outputBuffer: OutputBuffer = { stdout: [], stderr: [] };
	const baseUrl = await waitForGateway(process, outputBuffer);

	return { process, baseUrl };
}

async function stopGateway(process: SpawnedGateway): Promise<void> {
	process.kill();
	await settleProcess(process);
}

async function postWebhookEvent(
	baseUrl: URL,
	text: string,
	conversationId: string,
): Promise<void> {
	await assertResponseOk(
		await fetch(new URL("/channels/webhook/events", baseUrl), {
			method: "POST",
			headers: { "content-type": "application/json" },
			body: JSON.stringify({ text, senderId: "bench-user", conversationId }),
		}),
		"webhook event",
	);
}

async function writeConfig(
	configPath: string,
	options: E2eOptions = {},
): Promise<void> {
	const agentArgs = [dumbClientPath, ...(options.agentArgs ?? [])];
	const authLine = options.auth
		? `\n      auth: ${JSON.stringify(options.auth)},`
		: "";
	const stateConfig = options.state
		? `{ driver: "sqlite", path: ${JSON.stringify(options.state.path)} }`
		: `{ driver: "memory" }`;

	await Bun.write(
		configPath,
		`import { defineConfig } from "@acpantenna/config";

export default defineConfig({
  server: { host: "127.0.0.1", port: 0 },
  agents: {
    dumb: {
      command: "bun",
      args: ${JSON.stringify(agentArgs)},
      cwd: ${JSON.stringify(repoRoot)},${authLine}
    },
  },
  channels: {
    webhook: {
      type: "webhook",
      agent: "dumb",
      permissions: { inbound: { mode: "open" } },
    },
  },
  state: ${stateConfig},
});
`,
	);
}

function waitForGateway(
	gatewayProcess: SpawnedGateway,
	outputBuffer: OutputBuffer,
): Promise<URL> {
	let settled = false;

	return new Promise((resolveReady, rejectReady) => {
		const timeout = setTimeout(() => {
			rejectOnce(
				new Error(
					`Timed out waiting for acpantenna to listen.\n${formatOutput(outputBuffer)}`,
				),
			);
		}, 10_000);

		const resolveOnce = (url: URL) => {
			if (settled) {
				return;
			}

			settled = true;
			clearTimeout(timeout);
			resolveReady(url);
		};

		const rejectOnce = (error: Error) => {
			if (settled) {
				return;
			}

			settled = true;
			clearTimeout(timeout);
			rejectReady(error);
		};

		void readLines(gatewayProcess.stdout, (line) => {
			outputBuffer.stdout.push(line);
			const match = /acpantenna listening on (http:\/\/\S+)/.exec(line);

			if (match?.[1]) {
				resolveOnce(new URL(match[1]));
			}
		});

		void readLines(gatewayProcess.stderr, (line) => {
			outputBuffer.stderr.push(line);
		});

		void gatewayProcess.exited.then((exitCode) => {
			if (!settled) {
				rejectOnce(
					new Error(
						`acpantenna exited before listening with code ${exitCode}.\n${formatOutput(outputBuffer)}`,
					),
				);
			}
		});
	});
}

async function waitForOutboxReply(
	baseUrl: URL,
	expectedText: string,
): Promise<{ text?: string }> {
	const deadline = Date.now() + 5_000;
	let lastPayload: string | undefined;

	while (Date.now() < deadline) {
		const response = await fetch(new URL("/channels/webhook/outbox", baseUrl));

		if (response.ok) {
			const payload = (await response.json()) as OutboxPayload;
			lastPayload = JSON.stringify(payload);
			const message = payload.messages?.find(
				(candidate) => candidate.text === expectedText,
			);

			if (message) {
				return message;
			}
		} else {
			lastPayload = `${response.status} ${await response.text()}`;
		}

		await Bun.sleep(100);
	}

	throw new Error(
		`Timed out waiting for outbox reply ${JSON.stringify(expectedText)}. Last payload: ${lastPayload ?? "none"}`,
	);
}

async function readLines(
	stream: ReadableStream<Uint8Array>,
	onLine: (line: string) => void,
): Promise<void> {
	const reader = stream.getReader();
	const decoder = new TextDecoder();
	let buffer = "";

	while (true) {
		const readResult = await reader.read();

		if (readResult.done) {
			const line = buffer.trim();

			if (line) {
				onLine(line);
			}

			return;
		}

		buffer += decoder.decode(readResult.value, { stream: true });
		const lines = buffer.split(/\r?\n/);
		buffer = lines.pop() ?? "";

		for (const line of lines) {
			onLine(line);
		}
	}
}

async function assertResponseOk(
	response: Response,
	action: string,
): Promise<void> {
	if (response.ok) {
		return;
	}

	throw new Error(
		`${action} failed with ${response.status}: ${await response.text()}`,
	);
}

async function settleProcess(gatewayProcess: SpawnedGateway): Promise<void> {
	await Promise.race([
		gatewayProcess.exited.catch(() => undefined),
		Bun.sleep(1_000),
	]);
}

function formatOutput(outputBuffer: OutputBuffer): string {
	return [
		"stdout:",
		...outputBuffer.stdout.slice(-20),
		"stderr:",
		...outputBuffer.stderr.slice(-20),
	].join("\n");
}
